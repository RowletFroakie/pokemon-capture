def epicEncounter(Catch_rate, pokemon_caught, len_epic_list, wild_pkmnList):
    rarity = Catch_rate["Epic"]
    random_pkmn = random.randint(0, len_epic_list-1)
    random_pkmn = wild_pkmnList[1][random_pkmn]
    slowprint("You have encountered an Epic Pokemon!", 0.05)
    print(random_pkmn)

    while not pokemon_caught:
        ball = input("What pokeball will you use: ")
        ball = ball.capitalize()

        if ball == "Pokeball":
            capture = random.randint(1, 1000)
            shakes(rarity["Pokeball"], capture, random_pkmn)
            if capture <= rarity["Pokeball"]:
                slowprint("You have caught " + random_pkmn, 0.05)
                break

            else:
                slowprint("Shoot! It Was So Close Too!", 0.05)

        elif ball == "Greatball":
            capture = random.randint(1, 1000)
            shakes(rarity["Greatball"], capture, random_pkmn)
            if capture <= rarity["Greatball"]:
                slowprint("You have caught " + random_pkmn, 0.05)
                break

            else:
                slowprint("Shoot! It Was So Close Too!", 0.05)

        elif ball == "Ultraball":
            capture = random.randint(1, 1000)
            shakes(rarity["Ultraball"], capture, random_pkmn)
            if capture <= rarity["Ultraball"]:
                slowprint("You have caught " + random_pkmn, 0.05)
                break

            else:
                slowprint("Shoot! It Was So Close Too!", 0.05)

        elif ball == "Masterball":
            capture = 1001
            shakes(rarity["Masterball"], capture, random_pkmn)
            slowprint("You have caught " + random_pkmn, 0.05)
            break


        elif ball != "Pokeball" and ball != "Greatball" and ball != "Ultraball" and ball != "Masterball":
            print("INVALID")

    return random_pkmn